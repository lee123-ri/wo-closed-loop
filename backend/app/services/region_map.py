def province_to_region(name: str | None) -> str:
    """省份名 → 大区名；无法识别（含「不统计」「测试区」等占位）返回空串。"""
    if not name:
        return ""
    return _PROVINCE_REGION.get(str(name).strip(), "")


def region_check_sql(colname: str = "region") -> str:
    """生成数据库 CHECK 约束的 SQL 片段：{colname} 只能是七大区之一或 NULL。"""
    vals = ", ".join(f"'{r}'" for r in REGIONS)
    return f"{colname} IN ({vals}) OR {colname} IS NULL"


def normalize_region(value: str | None) -> str | None:
    """任意输入 → 标准大区（7 选 1）或 None。

    归一化优先级：已是标准大区 → 省份名 → 组织名（*区域子公司/中心/交付中心）。
    任何识别不了的非空值一律返回 None，保证落到库里的 region 只可能是七选一或空。
    """
    if not value:
        return None
    v = str(value).strip()
    if v in REGION_SET:
        return v
    r = province_to_region(v)
    if r:
        return r
    if v in _ORG_REGION:
        return _ORG_REGION[v]
    for k in REGIONS:  # 兜底：以标准大区开头的组织名，如「西北区域…」「华东…中心」
        if v.startswith(k):
            return k
    return None